import mongoose from 'mongoose';

const orderItemSchema = new mongoose.Schema({
  product: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'Product',
    required: true,
  },
  title: { type: String, required: true },
  image: { type: String, required: true },
  price: { type: Number, required: true },
  quantity: { type: Number, required: true, min: 1 },
  // Absent for products bought without a color variant (all existing
  // orders). `price` above is already the price of this specific variant
  // at purchase time when a color was selected.
  color: { type: String, default: undefined },
});

const orderSchema = new mongoose.Schema(
  {
    user: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: false,
    },
    orderItems: [orderItemSchema],
    shippingAddress: {
      fullName: { type: String, required: true },
      phone: { type: String, required: true },
      district: { type: String, required: true },
      thana: { type: String, required: true },
      area: { type: String, required: true },
      house: { type: String, default: '' },
      postalCode: { type: String, default: '' },
      deliveryInstructions: { type: String, default: '' },
      country: { type: String, required: true },
    },
    paymentMethod: {
      type: String,
      enum: ['cod'],
      default: 'cod',
    },
    itemsPrice: { type: Number, required: true, default: 0 },
    shippingPrice: { type: Number, required: true, default: 0 },
    totalPrice: { type: Number, required: true, default: 0 },
    // Which delivery-charge tier was used to compute shippingPrice, for
    // display/audit. Absent on orders placed before this existed.
    deliveryZone: { type: String, enum: ['dhaka', 'subcity', 'outside'], default: undefined },
    deliveryChargePhone: { type: String },
    // Idempotency key generated by the client for a single checkout submission.
    // A unique+sparse index guarantees a retried request (e.g. after a lost
    // response during a server restart) can never create a duplicate order.
    clientRequestId: { type: String },
    // Bearer secret for guest (no account) orders. Guest checkout has no user
    // to own the order, so the order id alone would let anyone who can
    // see/guess a Mongo ObjectId read another guest's name/phone/address or
    // rewrite their delivery-charge number (IDOR). This random token is
    // required in addition to the id for any guest order lookup/update; it is
    // returned once in the create-order response and carried by the client
    // (URL query param) from then on. Logged-in orders don't need it — those
    // are authorized by the owning user's JWT instead.
    guestAccessToken: { type: String, select: false },
    status: {
      type: String,
      enum: ['pending', 'processing', 'shipped', 'delivered', 'cancelled'],
      default: 'pending',
    },
    isPaid: { type: Boolean, default: false },
    paidAt: Date,
    isDelivered: { type: Boolean, default: false },
    deliveredAt: Date,
  },
  { timestamps: true }
);

orderSchema.index({ clientRequestId: 1 }, { unique: true, sparse: true });

const Order = mongoose.model('Order', orderSchema);
export default Order;
